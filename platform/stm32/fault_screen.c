static int glyph_index(char c)
{
    for (int i = 0; k_chars[i]; i++) {
        if (k_chars[i] == c) {
            return i;
        }
    }
    return (int)sizeof(k_chars) - 2; /* unbekannt -> Leerzeichen */
}

void fault_screen_draw(uint16_t *fb, int w, int h, const char *const *lines, int n)
{
    for (int i = 0; i < w * h; i++) {
        fb[i] = 0x8000; /* dunkelrot */
    }
    const int cell_w = (GLYPH_W + 1) * SCALE;
    const int line_h = (GLYPH_H + 2) * SCALE;
    for (int l = 0; l < n; l++) {
        int y0 = 10 + l * line_h;
        for (int c = 0; lines[l][c]; c++) {
            const uint8_t *g = k_glyph[glyph_index(lines[l][c])];
            int x0 = 10 + c * cell_w;
            for (int gy = 0; gy < GLYPH_H; gy++) {
                for (int gx = 0; gx < GLYPH_W; gx++) {
                    if (!(g[gy] & (1u << (GLYPH_W - 1 - gx)))) {
                        continue;
                    }
                    for (int sy = 0; sy < SCALE; sy++) {
                        for (int sx = 0; sx < SCALE; sx++) {
                            int x = x0 + gx * SCALE + sx;
                            int y = y0 + gy * SCALE + sy;
                            if (x < w && y < h) {
                                fb[y * w + x] = 0xFFFF;
                            }
                        }
                    }
                }
            }
        }
    }
}
